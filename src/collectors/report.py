"""Write docs/02_data_sources.md: row counts per source / ticker / year and every known gap.

    uv run python -m src.collectors.report

Reads the database read-only and only rows with available_at before the cutoff of the first
test day: the test period is never counted or described here (D-13, D-31).
"""

from __future__ import annotations

import argparse
import subprocess
from collections import defaultdict
from datetime import timedelta
from pathlib import Path
from typing import Any

import duckdb

from src.collectors.common import (
    ROOT,
    collectors_config,
    load_periods,
    load_universe,
    raw_dir,
    read_json,
    test_period,
    utc_now,
)
from src.collectors.quality import calendar, price_completeness, run_checks
from src.db import connect
from src.marketview.clock import cutoff_for

DEV = ("warmup", "train", "validation")
OUT = ROOT / "docs" / "02_data_sources.md"


def _rows(con: duckdb.DuckDBPyConnection, sql: str, params: list | None = None) -> list[tuple]:
    return con.execute(sql, params or []).fetchall()


def _table(header: list[str], rows: list[list[Any]]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def _cap(items: list[str], n: int = 40) -> str:
    """Comma list of at most n items, with the remainder counted."""
    head = ", ".join(items[:n])
    return head + (f", … (+{len(items) - n} more)" if len(items) > n else "")


def _git_sha() -> str:
    try:
        return subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True
        ).stdout.strip()
    except OSError:
        return "unknown"


def build(con: duckdb.DuckDBPyConnection) -> str:
    con.execute("SET TimeZone = 'UTC'")
    periods = load_periods(DEV)
    companies, benchmark = load_universe()
    tickers = [c.ticker for c in companies]
    sector = {c.ticker: c.sector for c in companies}
    cut = cutoff_for(test_period().start)
    summary = read_json(raw_dir() / "collect_summary_warmup_train_validation.json") or {}
    fh_cfg = collectors_config()["finnhub"]

    years = [r[0] for r in _rows(con, "SELECT DISTINCT year(bar_date) FROM price_bars "
                                      "WHERE available_at < ? ORDER BY 1", [cut])]  # fmt: skip
    counts: dict[str, dict[tuple[str, int], int]] = defaultdict(dict)
    queries = {
        "prices": "SELECT ticker, year(bar_date), count(*) FROM price_bars",
        "news": "SELECT ticker, year(available_at), count(*) FROM news",
        "8-K": "SELECT ticker, year(available_at), count(*) FROM filings",
        "10-Q/10-K": "SELECT ticker, year(available_at), count(*) FROM filings",
        "Form 4": "SELECT ticker, year(available_at), count(*) FROM filings",
        "facts": "SELECT ticker, year(available_at), count(*) FROM facts",
    }
    where = {"8-K": "form = '8-K'", "10-Q/10-K": "form IN ('10-Q', '10-K')", "Form 4": "form = '4'"}
    for src, sql in queries.items():
        cond = " AND ".join(x for x in ["available_at < ?", where.get(src, "")] if x)
        for t, y, n in _rows(con, f"{sql} WHERE {cond} GROUP BY ALL", [cut]):
            counts[src][(t, y)] = n

    lines = [
        "# 02 — Data sources: coverage and gaps",
        "",
        f"Generated by `uv run python -m src.collectors.report` at {utc_now():%Y-%m-%d %H:%M} UTC "
        f"(git `{_git_sha()}`). CRISP-DM phase 3 (data preparation). Do not edit by hand.",
        "",
        "Scope: the development periods only "
        + ", ".join(f"**{p.name}** {p.start}..{p.end}" for p in periods)
        + f". Rows available at or after {cut:%Y-%m-%d %H:%M} UTC (the cutoff of the first test "
        "day) are excluded; the test period has **not been collected** (D-31).",
        "",
        "## Sources",
        "",
        _table(
            ["Source", "Table", "available_at (D-24, D-30)", "Limits / notes"],
            [
                [
                    "yfinance daily bars (Stooq fallback)",
                    "price_bars",
                    "16:00 ET bar close",
                    "split-adjusted, not dividend-adjusted (D-29)",
                ],
                [
                    "Finnhub company news",
                    "news",
                    "provider `datetime`",
                    f"{fh_cfg['calls_per_minute']}/min; free window ~1 year; ≤ ~250 items/call",
                ],
                [
                    "SEC EDGAR submissions",
                    "filings",
                    "`acceptanceDateTime` (UTC)",
                    "8-K items from the index; EX-99.1 text; ≤ 8 req/s with SEC_USER_AGENT",
                ],
                [
                    "SEC XBRL companyfacts",
                    "facts",
                    "acceptance of the carrying 10-Q/10-K",
                    "revenue, diluted EPS, net income; own reporting period only",
                ],
            ],
        ),  # fmt: skip
        "",
        "## Totals per source and year",
        "",
    ]
    tot_rows = []
    for src in queries:
        per_year = defaultdict(int)
        for (_, y), n in counts[src].items():
            per_year[y] += n
        tot_rows.append([src, *[f"{per_year.get(y, 0):,}" for y in years],
                         f"{sum(per_year.values()):,}"])  # fmt: skip
    lines += [_table(["Source", *map(str, years), "Total"], tot_rows), ""]

    lines += [
        "## Rows per ticker and year",
        "",
        "Columns: prices = daily bars; news = Finnhub articles tagged with the ticker; "
        "8-K / 10-Q+10-K / Form 4 = filings by acceptance year; facts = XBRL facts.",
        "",
    ]
    header = ["Ticker", "Sector"]
    for src in queries:
        header += [f"{src} {str(y)[2:]}" for y in years]
    rows = []
    for t in [benchmark, *tickers]:
        r = [t, sector.get(t, "benchmark")]
        for src in queries:
            r += [counts[src].get((t, y), 0) for y in years]
        rows.append(r)
    lines += [_table(header, rows), ""]

    # ------------------------------------------------------------------ gaps
    lines += ["## Gaps", ""]
    sessions = [d for p in periods for d in calendar(con, benchmark, p)]
    holidays: list[str] = []
    for p in periods:  # weekdays between the period's first and last session without a session
        ps = set(calendar(con, benchmark, p))
        if not ps:
            holidays.append(f"(no SPY bars in {p.name})")
            continue
        d = min(ps)
        while d <= max(ps):
            if d.weekday() < 5 and d not in ps:
                holidays.append(d.isoformat())
            d += timedelta(days=1)
    lines += [
        f"**Exchange calendar.** {len(sessions)} SPY sessions; weekdays without a session (should "
        f"be exactly the NYSE holidays): {_cap(holidays)}.",
        "",
    ]
    comp = price_completeness(con, tickers, benchmark, periods)
    target = float(collectors_config()["prices"]["min_completeness"])
    low = {t: v for t, v in comp.items() if v["completeness"] < target}
    mean = sum(v["completeness"] for v in comp.values()) / len(comp) if comp else 0.0
    lines.append(
        f"**Prices.** Mean session completeness {mean:.4f} over {len(comp)} tickers "
        f"(target ≥ {target}). "
        + (
            "Below target: "
            + _cap(
                [
                    f"{t} {v['present']}/{v['expected']} (missing {_cap(v['missing'], 6)})"
                    for t, v in low.items()
                ],
                20,
            )
            if low
            else "No ticker below target."
        )  # fmt: skip
    )
    providers = (summary.get("prices") or {}).get("by_provider", {})
    if providers:
        lines.append(f"Bars by provider: {providers}.")
    lines.append("")

    # news: free-window clip, zero months, truncated days
    news_stats = summary.get("news") or {}
    first_news = _rows(con, "SELECT min(available_at) FROM news WHERE available_at < ?", [cut])[0][
        0
    ]
    lines.append(
        f"**News.** First stored article {first_news:%Y-%m-%d} (Finnhub free window, D-29); "
        "the warmup period before that has no news by design. "
        + (f"Skipped: {news_stats.get('skipped')}. " if news_stats.get("skipped") else "")
        + f"Finnhub calls in the last collect: {news_stats.get('calls', 'n/a')}."
    )
    months = _rows(
        con,
        "SELECT ticker, strftime(available_at, '%Y-%m') m, count(*) FROM news "
        "WHERE available_at < ? AND available_at >= ? GROUP BY ALL",
        [cut, cutoff_for(load_periods(["train"])[0].start)],
    )
    by_tm = {(t, m): n for t, m, n in months}
    all_months = sorted({m for _, m, _ in months})
    thin = [(t, m, by_tm.get((t, m), 0)) for t in tickers for m in all_months
            if by_tm.get((t, m), 0) < 10]  # fmt: skip
    lines.append(
        f"Ticker-months in train+validation with fewer than 10 articles: {len(thin)} of "
        f"{len(tickers) * len(all_months)}"
        + (": " + _cap([f"{t} {m} ({n})" for t, m, n in thin], 60) if thin else "")
        + "."
    )
    trunc = news_stats.get("truncated_days") or []
    lines.append(
        f"Days still at the per-call cap after splitting to one day (possibly truncated): "
        f"{len(trunc)}" + (": " + _cap(trunc) if trunc else "") + "."
    )
    per_ticker_news = _rows(con, "SELECT ticker, count(*) FROM news WHERE available_at < ? "
                                 "GROUP BY 1 ORDER BY 2", [cut])  # fmt: skip
    if per_ticker_news:
        lo, hi = per_ticker_news[0], per_ticker_news[-1]
        lines.append(f"Fewest articles: {lo[0]} ({lo[1]:,}); most: {hi[0]} ({hi[1]:,}).")
    lines.append("")

    # filings
    f_stats = summary.get("filings") or {}
    no_text = _rows(con, "SELECT count(*) FROM filings WHERE form = '8-K' AND text_path IS NULL "
                         "AND available_at < ?", [cut])[0][0]  # fmt: skip
    periodic = {
        (t, y): n
        for t, y, n in _rows(
            con,
            "SELECT ticker, year(available_at), count(*) FROM filings "
            "WHERE form IN ('10-Q', '10-K') AND available_at < ? GROUP BY ALL",
            [cut],
        )
    }
    odd = [f"{t} {y}: {periodic.get((t, y), 0)}" for t in tickers for y in (2024, 2025)
           if periodic.get((t, y), 0) != 4]  # fmt: skip
    lines += [
        f"**Filings.** 8-Ks without stored text: {no_text}"
        + (f" (last collect: {f_stats.get('texts')} texts, {f_stats.get('text_missing')} "
           "missing)" if f_stats else "") + ". "
        "Full years 2024 and 2025 should hold exactly 4 periodic reports (3 × 10-Q + 1 × 10-K); "
        + (f"exceptions: {_cap(odd)}." if odd else "no exceptions."),
        "",
    ]  # fmt: skip

    # facts
    have = {
        (t, n)
        for t, n in _rows(
            con, "SELECT DISTINCT ticker, name FROM facts WHERE available_at < ?", [cut]
        )
    }
    missing_facts = [f"{t}:{n}" for t in tickers for n in ("revenue", "eps_diluted", "net_income")
                     if (t, n) not in have]  # fmt: skip
    x_stats = summary.get("xbrl") or {}
    lines += [
        "**XBRL facts.** Missing concept series (no fact at all in the dev periods): "
        + (_cap(missing_facts) if missing_facts else "none") + ". "
        f"Facts stamped with the 22:00 ET fallback instead of an acceptance time: "
        f"{x_stats.get('fallback_time', 'n/a')}.",
        "",
        "**Not collected.** Test period (D-31); Binance crypto candles (Should item); FNSPID "
        "(cannot cover the frozen splits, D-29).",
        "",
    ]  # fmt: skip

    # quality checks, 8-K items
    rep = run_checks(con, periods, tickers, benchmark)
    lines += [
        "## Quality checks (src/collectors/quality.py)",
        "",
        f"Failures: {len(rep.failures)}" + ("".join(f"\n- {f}" for f in rep.failures)),
        "",
        f"Warnings: {len(rep.warnings)}"
        + "".join(f"\n- {w}" for w in rep.warnings[:40])
        + ("\n- …" if len(rep.warnings) > 40 else ""),
        "",
        f"News duplicate share (ticker, url): {rep.metrics.get('news_duplicate_share', 0):.4f}.",
        "",
        "## 8-K item distribution (dev periods)",
        "",
    ]
    items = _rows(
        con,
        "SELECT item, count(*) FROM (SELECT unnest(items) AS item FROM filings "
        "WHERE form = '8-K' AND available_at < ?) GROUP BY 1 ORDER BY 2 DESC",
        [cut],
    )
    lines += [_table(["Item", "8-Ks"], [[i, n] for i, n in items]), ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--db", default=None)
    ap.add_argument("--out", default=str(OUT))
    args = ap.parse_args(argv)
    con = connect(Path(args.db) if args.db else None)
    try:
        text = build(con)
    finally:
        con.close()
    Path(args.out).write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
